package harness

import (
	"fmt"
	"io/fs"
	"path"
	"sort"
	"strings"
)

// Marker is the first line of every file sh-agent generates. Install and
// uninstall use it to tell a file sh-agent owns from one the operator wrote.
// Its wording is frozen: changing it would make every earlier install look
// foreign.
const Marker = "<!-- generated by sh-agent from the styrman-harness repo: edit context/*.md, agents/ or skills/ there and run `sh-agent install` -->"

// claudeStub is the one-line ~/.claude/CLAUDE.md that pulls in AGENTS.md, so
// the canonical file keeps the agents.md name on both vendors.
const claudeStub = Marker + "\n@AGENTS.md\n"

// RenderContext assembles the deployed context: context/AGENTS.md first,
// every other context/*.md in name order, then the compact inventory.
func RenderContext(src Source, inv Inventory) ([]byte, error) {
	if err := checkManagedTree(src); err != nil {
		return nil, err
	}
	main, err := fs.ReadFile(src.FS, "context/AGENTS.md")
	if err != nil {
		return nil, fmt.Errorf("reading context: %w", err)
	}
	extras, err := fs.Glob(src.FS, "context/*.md")
	if err != nil {
		return nil, err
	}
	sort.Strings(extras)

	var b strings.Builder
	b.WriteString(Marker + "\n")
	b.Write(main)
	for _, p := range extras {
		if path.Base(p) == "AGENTS.md" {
			continue
		}
		data, err := fs.ReadFile(src.FS, p)
		if err != nil {
			return nil, err
		}
		b.WriteString("\n")
		b.Write(data)
	}
	b.WriteString("\n")
	b.WriteString(RenderInventoryCompact(inv))
	return []byte(b.String()), nil
}
